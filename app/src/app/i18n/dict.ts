export const dict: Record<Lang, Partial<Record<TKey, string>>> = { en, fr, ar }

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  const raw = dict[lang][key] ?? en[key]
  if (!vars) return raw
  return Object.entries(vars).reduce((out, [name, value]) => out.replaceAll(`{${name}}`, String(value)), raw)
}

export const dirFor = (lang: Lang): 'rtl' | 'ltr' => LANGUAGES.find((l) => l.key === lang)?.dir ?? 'ltr'
